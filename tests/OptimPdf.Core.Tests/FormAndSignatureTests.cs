public class FormTests
{
    static readonly PdfRect NameRect = new(100, 600, 400, 625);
    static readonly PdfRect AgreeRect = new(100, 550, 118, 568);

    static byte[] FormPdf() => DocumentSession.Transform(TestPdf.Blank(2), null, doc =>
    {
        FormBuilder.AddTextField(doc, 0, "name", NameRect);
        FormBuilder.AddCheckBox(doc, 1, "agree", AgreeRect);

        // A combo box, built by hand as other producers write them.
        var combo = new PdfDictionary(doc);
        combo.Elements.SetName("/Type", "/Annot");
        combo.Elements.SetName("/Subtype", "/Widget");
        combo.Elements.SetName("/FT", "/Ch");
        combo.Elements.SetInteger("/Ff", 1 << 17);
        combo.Elements.SetString("/T", "color");
        combo.Elements["/Rect"] = PdfObjects.Numbers(doc, 100, 500, 250, 520);
        var opt = new PdfArray(doc);
        opt.Elements.Add(new PdfString("Red"));
        var pair = new PdfArray(doc);
        pair.Elements.Add(new PdfString("G"));
        pair.Elements.Add(new PdfString("Green"));
        opt.Elements.Add(pair);
        combo.Elements["/Opt"] = opt;
        combo.Elements.SetString("/DA", "/Helv 10 Tf 0 g");
        doc.Internals.AddObject(combo);
        doc.Pages[0].Elements.GetArray("/Annots")!.Elements.Add(combo.Reference!);
        doc.Internals.Catalog.Elements.GetDictionary("/AcroForm")!.Elements.GetArray("/Fields")!.Elements.Add(combo.Reference!);
    });

    [Fact]
    public void Lists_fields_with_kinds_pages_and_positions()
    {
        var fields = DocumentSession.FromBytes(FormPdf()).Query(FormService.ListFields);
        Assert.Equal(["name", "agree", "color"], fields.Select(f => f.Name));
        Assert.Equal([FormFieldKind.Text, FormFieldKind.CheckBox, FormFieldKind.ComboBox], fields.Select(f => f.Kind));
        Assert.Equal([0, 1, 0], fields.Select(f => f.PageIndex));
        Assert.Equal(NameRect, fields[0].Rect);
        Assert.Equal(["Red", "Green"], fields[2].Options);
        Assert.Equal("false", fields[1].Value);
    }

    [Fact]
    public void Fills_text_checkbox_and_choice_values()
    {
        using var session = DocumentSession.FromBytes(FormPdf());
        session.Apply("Fill", doc =>
        {
            FormService.SetValue(doc, "name", "Ada Lovelace");
            FormService.SetValue(doc, "agree", "true");
            FormService.SetValue(doc, "color", "Green");
        });
        var fields = session.Query(FormService.ListFields).ToDictionary(f => f.Name);
        Assert.Equal("Ada Lovelace", fields["name"].Value);
        Assert.Equal("true", fields["agree"].Value);
        Assert.Equal("Green", fields["color"].Value);
        // Appearances are generated by Optim PDF, so viewers are told to use them as-is.
        Assert.False(session.Query(d => d.AcroForm!.Elements.GetBoolean("/NeedAppearances")));
    }

    [Fact]
    public void Filled_values_are_visible_when_rendered()
    {
        var filled = DocumentSession.Transform(FormPdf(), null, doc =>
        {
            FormService.SetValue(doc, "name", "Ada Lovelace");
            FormService.SetValue(doc, "agree", "true");
        });
        using var r = PdfiumDocument.Open(filled);
        Assert.True(DarkPixels(r, 0, NameRect) > 40, "Text field value should be drawn.");
        Assert.True(DarkPixels(r, 1, AgreeRect) > DarkPixels(PdfiumDocument.Open(FormPdf()), 1, AgreeRect) + 10, "Check mark should be drawn.");
    }

    [Fact]
    public void Flatten_keeps_values_as_page_content()
    {
        var flat = DocumentSession.Transform(FormPdf(), null, doc =>
        {
            FormService.SetValue(doc, "name", "Grace Hopper");
            FormService.Flatten(doc);
        });
        Assert.Empty(DocumentSession.FromBytes(flat).Query(FormService.ListFields));
        using var r = PdfiumDocument.Open(flat);
        Assert.True(DarkPixels(r, 0, NameRect) > 40);
    }

    [Fact]
    public void Rejects_unknown_fields_bad_options_and_read_only()
    {
        Assert.Throws<KeyNotFoundException>(() => DocumentSession.Transform(FormPdf(), null, d => FormService.SetValue(d, "missing", "x")));
        Assert.Throws<ArgumentException>(() => DocumentSession.Transform(FormPdf(), null, d => FormService.SetValue(d, "color", "Purple")));
        var readOnly = DocumentSession.Transform(FormPdf(), null, d => d.AcroForm!.Fields["name"]!.ReadOnly = true);
        Assert.Throws<InvalidOperationException>(() => DocumentSession.Transform(readOnly, null, d => FormService.SetValue(d, "name", "x")));
    }

    [Fact]
    public void Builder_rejects_duplicate_and_dotted_names()
    {
        Assert.Throws<ArgumentException>(() => DocumentSession.Transform(FormPdf(), null, d => FormBuilder.AddTextField(d, 0, "name", NameRect)));
        Assert.Throws<ArgumentException>(() => DocumentSession.Transform(FormPdf(), null, d => FormBuilder.AddTextField(d, 0, "a.b", NameRect)));
    }

    static int DarkPixels(PdfiumDocument r, int page, PdfRect rect)
    {
        var bmp = r.Render(page, 1);
        var (x1, y1) = r.PageToDevice(page, bmp.PixelWidth, bmp.PixelHeight, 0, rect.Left, rect.Top);
        var (x2, y2) = r.PageToDevice(page, bmp.PixelWidth, bmp.PixelHeight, 0, rect.Right, rect.Bottom);
        int n = 0;
        for (int y = Math.Max(0, y1 + 2); y < Math.Min(bmp.PixelHeight, y2 - 2); y++)
            for (int x = Math.Max(0, x1 + 2); x < Math.Min(bmp.PixelWidth, x2 - 2); x++)
                if (bmp.Pixels[y * bmp.Stride + x * 4 + 1] < 128) n++;
        return n;
    }
}

public class SignatureTests
{
    static readonly PdfRect Box = new(100, 220, 300, 300);

    static int InkPixels(byte[] data, PdfRect rect)
    {
        using var r = PdfiumDocument.Open(data);
        var bmp = r.Render(0, 1);
        var (x1, y1) = r.PageToDevice(0, bmp.PixelWidth, bmp.PixelHeight, 0, rect.Left, rect.Top);
        var (x2, y2) = r.PageToDevice(0, bmp.PixelWidth, bmp.PixelHeight, 0, rect.Right, rect.Bottom);
        int n = 0;
        for (int y = Math.Max(0, Math.Min(y1, y2)); y < Math.Min(bmp.PixelHeight, Math.Max(y1, y2)); y++)
            for (int x = Math.Max(0, Math.Min(x1, x2)); x < Math.Min(bmp.PixelWidth, Math.Max(x1, x2)); x++)
            {
                int o = y * bmp.Stride + x * 4;
                if (bmp.Pixels[o + 2] < 150 && bmp.Pixels[o] > bmp.Pixels[o + 2]) n++; // Bluish ink.
            }
        return n;
    }

    static readonly DrawnSignature Drawn = DrawnSignature.FromStrokes([
        Enumerable.Range(0, 60).Select(i => new SignaturePoint(i * 5, 40 + 30 * Math.Sin(i / 5.0))).ToList(),
        [new SignaturePoint(20, 10), new SignaturePoint(260, 90)],
    ]);

    [Fact]
    public void Drawn_signature_renders_inside_box_with_proportions()
    {
        PdfRect placed = default;
        var data = DocumentSession.Transform(TestPdf.Blank(), null, doc =>
            placed = VisualSignatureService.Place(doc, 0, Box.Left, Box.Top, Box.Width, Box.Height, Drawn));
        Assert.True(placed.Width <= Box.Width + 0.5 && placed.Height <= Box.Height + 0.5);
        Assert.Equal(Drawn.AspectRatio, placed.Width / placed.Height, 2);
        Assert.True(InkPixels(data, Box) > 150);
        Assert.Equal(0, InkPixels(data, new PdfRect(320, 220, 500, 300)));
    }

    [Fact]
    public void Typed_signature_uses_a_script_font()
    {
        var data = DocumentSession.Transform(TestPdf.Blank(), null, doc =>
            VisualSignatureService.Place(doc, 0, Box.Left, Box.Top, Box.Width, Box.Height, new TypedSignature("Ada Lovelace")));
        Assert.True(InkPixels(data, Box) > 150);
        var fonts = DocumentSession.FromBytes(data).Query(d => d.Internals.GetAllObjects().OfType<PdfDictionary>()
            .Where(o => o.Elements.GetName("/Type") == "/Font").Select(o => o.Elements.GetName("/BaseFont")).ToList());
        Assert.Contains(fonts, f => f.EndsWith("+Segoe Script")); // Embedded as a subset.
    }

    [Fact]
    public void Image_signature_keeps_transparency()
    {
        using var bmp = new Bitmap(200, 80);
        using (var g = Graphics.FromImage(bmp))
        {
            g.Clear(Color.Transparent);
            g.FillEllipse(Brushes.Navy, 20, 20, 160, 40);
        }
        var png = ImageCodec.Encode(bmp, ImageFileFormat.Png);
        var data = DocumentSession.Transform(TestPdf.Create(1), null, doc =>
            VisualSignatureService.Place(doc, 0, Box.Left, Box.Top, Box.Width, Box.Height, ImageSignature.FromImage(png)));
        Assert.True(InkPixels(data, Box) > 500);
        // Corners of the image are transparent, so the page (white) shows through.
        using var r = PdfiumDocument.Open(data);
        var (red, _, _) = TestPdf.AverageColor(r, 0, new PdfRect(Box.Left + 1, Box.Top - 6, Box.Left + 6, Box.Top - 1));
        Assert.True(red > 240);
    }

    [Fact]
    public void Signature_on_rotated_page_stays_in_bounds()
    {
        PdfRect placed = default;
        var data = DocumentSession.Transform(TestPdf.Blank(), null, doc =>
        {
            PageOperations.Rotate(doc, [0], 270);
            placed = VisualSignatureService.Place(doc, 0, 300, 400, 200, 80, Drawn);
        });
        Assert.True(InkPixels(data, placed) > 150);
    }

    [Fact]
    public void Signatures_round_trip_through_json()
    {
        var marks = new SignatureMark[] { Drawn, new TypedSignature("A. L."), new ImageSignature([1, 2, 3], 2.5) };
        var json = JsonSerializer.Serialize(marks);
        var back = JsonSerializer.Deserialize<SignatureMark[]>(json)!;
        Assert.IsType<DrawnSignature>(back[0]);
        Assert.Equal(Drawn.Strokes.Count, ((DrawnSignature)back[0]).Strokes.Count);
        Assert.Equal("A. L.", ((TypedSignature)back[1]).Text);
        Assert.Equal([1, 2, 3], ((ImageSignature)back[2]).ImageData);
    }

    [Fact]
    public void Empty_drawing_is_rejected()
    {
        Assert.Throws<ArgumentException>(() => DrawnSignature.FromStrokes([]));
    }
}
